func TestExportAuthGating(t *testing.T) {
	h := Handler(Opts{Prefix: "/apidoc", Store: newTestStore(),
		Auth: auth.Config{Enable: true, Password: "pw", Secret: "sec", Expire: time.Hour}})
	if rec := req(t, h, http.MethodGet, "/api/export?format=json", ""); rec.Code != http.StatusUnauthorized {
		t.Fatalf("export without cookie: want 401 got %d", rec.Code)
	}
	if rec := req(t, h, http.MethodGet, "/api/export?format=typescript", ""); rec.Code != http.StatusUnauthorized {
		t.Fatalf("export ts without cookie: want 401 got %d", rec.Code)
	}
	login := req(t, h, http.MethodPost, "/api/login", `{"password":"pw"}`)
	if login.Code != http.StatusOK {
		t.Fatalf("login: %d %s", login.Code, login.Body.String())
	}
	cookies := login.Result().Cookies()
	if rec := req(t, h, http.MethodGet, "/api/export?format=json", "", cookies[0]); rec.Code != http.StatusOK {
		t.Fatalf("export with cookie: want 200 got %d", rec.Code)
	}
}
